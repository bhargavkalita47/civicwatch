import { existsSync, readFileSync } from 'node:fs';
import { strict as assert } from 'node:assert';
const read = (path) => readFileSync(path, 'utf8');
const map = read('src/components/CivicMap.tsx');
const modal = read('src/components/Forms.tsx');
const place = read('src/components/PlaceSearch.tsx');
const thread = read('src/components/ThreadPanel.tsx');
const app = read('src/App.tsx');
const auth = read('src/services/auth.tsx');
const mobile = read('src/mobile-nav.css');
const search = read('src/explore.css');
const theme = read('src/hierarchy.css');
const html = read('index.html');
const vercel = JSON.parse(read('vercel.json'));
const headers = read('public/_headers');
const mobileStack = /\.mobile-topbar\s*\{[\s\S]*?z-index:\s*(\d+)/.exec(mobile);
const searchStack = /\.explore-toolbar\s*\{[\s\S]*?z-index:\s*(\d+)/.exec(search);
assert.ok(mobileStack && searchStack && +mobileStack[1] > +searchStack[1], 'Mobile topbar must be above Explore search');
assert.doesNotMatch(place, /<form\b/, 'Place search may not nest a form in the reporting modal');
for (const label of ['Zoom in','Zoom out'])
  assert.match(map, new RegExp(`<button type="button"[^\\n]*aria-label="${label}"`), `${label} must not submit the report form`);
assert.match(map, /--pin-ink:\$\{markerIconColor\(bg\)\}/, 'Use accessible ink on all density variants');
assert.match(theme, /color:\s*var\(--pin-ink/, 'Pin icons must not be white by default');
assert.match(modal, /createdIssue\.current\s*=\s*issue/, 'Remember created report before refresh');
assert.match(thread, /onCommentCreated\(comment\)/, 'Display saved comments before refresh');
assert.match(app, /status: tab === "explore" \? "all"/, 'Resolved filters must never hide the Explore map');
assert.match(app, /<header className="mobile-topbar"/, 'Mobile navigation needs a banner landmark');
assert.match(auth, /addEventListener\("storage", onStorage\)/, 'Synchronize preview session across tabs');
assert.match(auth, /new BroadcastChannel\("civicwatch-auth-v1"\)/, 'Synchronize eventual API sessions across tabs');
assert.doesNotMatch(html, /<script\s*>/, 'Inline scripts violate strict Content Security Policy');
assert.ok(existsSync('public/theme-init.js'));
assert.match(html, /src="\/theme-init\.js"/);
assert.equal(vercel.framework, 'vite');
assert.equal(vercel.outputDirectory, 'dist');
const policy = vercel.headers[0].headers.find(({key}) => key === 'Content-Security-Policy')?.value;
assert.ok(policy && headers.includes(policy), 'Cloudflare and Vercel must have matching security policies');
assert.ok(!vercel.rewrites, 'Do not rewrite future API calls into the SPA');
console.log('Release regressions: mobile nav, nested forms, safe writes, cross-tab auth, palette, CSP and Vercel: OK');
